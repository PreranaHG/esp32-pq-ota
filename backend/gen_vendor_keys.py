import os
import oqs

ALG = "ML-DSA-44"

if os.path.exists("vendor_dsa_sk.bin"):
    raise SystemExit("vendor_dsa_sk.bin already exists - refusing to overwrite your signing key.")

with oqs.Signature(ALG) as signer:
    pk = signer.generate_keypair()
    sk = signer.export_secret_key()

with open("vendor_dsa_sk.bin", "wb") as f:
    f.write(sk)
with open("vendor_dsa_pk.bin", "wb") as f:
    f.write(pk)

lines = []
for i in range(0, len(pk), 16):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in pk[i:i + 16]) + ",")

header = f"""#ifndef VENDOR_DSA_PK_H
#define VENDOR_DSA_PK_H

#include <stdint.h>
#include "mldsa_native.h"

// Generated by gen_vendor_keys.py ({ALG}, {len(pk)} bytes)
static const uint8_t VENDOR_DSA_PK[MLDSA44_PUBLICKEYBYTES] = {{
{chr(10).join(lines)}
}};

#endif // VENDOR_DSA_PK_H
"""
with open("vendor_dsa_pk.h", "w") as f:
    f.write(header)

print(f"pk = {len(pk)} bytes, sk = {len(sk)} bytes")
print("Wrote vendor_dsa_sk.bin, vendor_dsa_pk.bin, vendor_dsa_pk.h")